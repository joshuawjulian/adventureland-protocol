def go_ident(name):
    p = pascal(name)
    if not p or not p[0].isalpha():
        p = "X" + p
    return p


class Go(Lang):
    PRIM = {"string": "string", "integer": "int64", "number": "float64", "boolean": "bool",
            "null": "any", "any": "any", "object": "map[string]any"}

    def t(self, tree):
        tree, _ = self.split_null(tree)
        p = self.prim(tree)
        if p:
            return self.PRIM[p]
        kind = tree[0]
        if kind == "prim":
            return self.PRIM[tree[1]]
        if kind == "ref":
            return tree[1]
        if kind == "array":
            return "[]" + self.t(tree[1])
        if kind == "record":
            return "map[string]" + self.t(tree[1])
        if kind == "tuple":
            return "[]any"  # a JSON array of mixed values
        return "json.RawMessage"  # a union of shapes: decode by hand

    def field_type(self, f):
        tree, nullable = self.split_null(parse_type(f["type"]))
        t = self.t(tree)
        # Optional and nullable scalars and structs become pointers, so "absent" is nil. Slices,
        # maps and raw JSON are nil already. Named structs are always pointers: a struct that
        # holds itself through a chain of fields would otherwise have infinite size.
        if t.startswith(("[]", "map[")) or t in ("any", "json.RawMessage"):
            return t
        if t in self.objects or f.get("optional") or nullable:
            return "*" + t
        return t

    def render(self):
        out = [f"// {HEADER}", "", "// Package alapi holds the types of the Adventure Land socket API.",
               "package alapi", "", 'import "encoding/json"', "",
               "// RawJSON keeps the import used when no type needs it.", "type RawJSON = json.RawMessage", ""]
        for kind, name, doc, body in self.m.decls:
            out += wrap(f"{name}: {doc}", prefix="// ")
            if kind == "object":
                fs = self.fields(body)
                idents = unique_names([f["name"] for f in fs], go_ident, {"Extra"})
                out.append(f"type {name} struct {{")
                for f in fs:
                    tag = f["name"] + (",omitempty" if f.get("optional") else "")
                    out.append(f"\t{idents[f['name']]} {self.field_type(f)} `json:{json.dumps(tag)}`")
                if self.is_open(body):
                    out.append("\t// Extra holds the keys this struct does not name (needs a custom UnmarshalJSON).")
                    out.append('\tExtra map[string]json.RawMessage `json:"-"`')
                out.append("}")
            elif kind == "alias":
                tree = parse_type(body)
                t = self.t(tree)
                if t == name:
                    t = "json.RawMessage"
                out.append(f"type {name} = {t}")
            else:
                out.append("// One of: " + ", ".join(body) + ".")
                p = self.prim(("union", [parse_type(x) for x in body]))
                out.append(f"type {name} = {self.PRIM[p] if p else 'json.RawMessage'}")
            out.append("")
        return "\n".join(out)


