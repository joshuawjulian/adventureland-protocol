def camel(name):
    p = pascal(name)
    s = (p[:1].lower() + p[1:]) or "field"
    if s[0].isdigit():
        s = "n" + s
    return s + "_" if s in JAVA_RESERVED else s


class Java(Lang):
    PRIM = {"string": "String", "integer": "Long", "number": "Double", "boolean": "Boolean",
            "null": "JsonNode", "any": "JsonNode", "object": "Map<String, JsonNode>"}

    def t(self, tree, seen=()):
        tree, _ = self.split_null(tree)
        p = self.prim(tree)
        if p:
            return self.PRIM[p]
        kind = tree[0]
        if kind == "prim":
            return self.PRIM[tree[1]]
        if kind == "ref":
            tg = self.target(tree[1], seen)
            if tg[0] == "object":
                return tree[1]
            if tg[0] == "tree" and tree[1] not in seen:
                return self.t(tg[1], seen + (tree[1],))
            if tg[0] == "union" and self.sealed(tree[1]):
                return tree[1]
            return "JsonNode"
        if kind == "array":
            return f"List<{self.t(tree[1], seen)}>"
        if kind == "record":
            return f"Map<String, {self.t(tree[1], seen)}>"
        return "JsonNode"

    def sealed(self, name):
        """A declared union whose members are all records: a sealed interface."""
        return all(x in self.objects for x in self.unions[name])

    def render(self):
        impls = {}
        for name, members in self.unions.items():
            if self.sealed(name):
                for x in members:
                    impls.setdefault(x, []).append(name)
        out = [f"// {HEADER}", "package alapi;", "",
               "import com.fasterxml.jackson.annotation.JsonIgnoreProperties;",
               "import com.fasterxml.jackson.annotation.JsonInclude;",
               "import com.fasterxml.jackson.annotation.JsonProperty;",
               "import com.fasterxml.jackson.databind.JsonNode;", "import java.util.List;",
               "import java.util.Map;", "",
               "/** The types of the Adventure Land socket API, as nested records. */",
               "public final class AlApi {", "    private AlApi() {}", ""]
        for kind, name, doc, body in self.m.decls:
            out.append("    /** " + doc_text(doc).replace("*/", "* /").replace("@", "{@literal @}") + " */")
            if kind == "object":
                fs = self.fields(body)
                idents = unique_names([f["name"] for f in fs], camel)
                comps = [f"@JsonProperty({json.dumps(f['name'])}) {self.t(parse_type(f['type']))} {idents[f['name']]}"
                         for f in fs]
                ann = "@JsonInclude(JsonInclude.Include.NON_NULL)"
                if self.is_open(body):
                    ann += " @JsonIgnoreProperties(ignoreUnknown = true)"
                imp = f" implements {', '.join(impls[name])}" if name in impls else ""
                out.append(f"    {ann}")
                out.append(f"    public record {name}(" + (
                    "\n        " + ",\n        ".join(comps) + ")" if comps else ")") + f"{imp} {{}}")
            elif kind == "union" and self.sealed(name):
                out.append(f"    public sealed interface {name} permits {', '.join(dict.fromkeys(body))} {{}}")
            else:
                what = body if kind == "alias" else " | ".join(body)
                out.append(f"    // {name} = {what} (inlined at each use)")
            out.append("")
        out.append("}")
        return "\n".join(out) + "\n"


GENERATORS = {"python": Python, "go": Go, "csharp": CSharp, "rust": Rust, "java": Java}


def generate(lang, schema=None):
    schema = schema or apischema.Schema()
    if lang == "ts":
        return apischema.typescript(schema)
    return GENERATORS[lang](schema).render()


def main():
    args = sys.argv[1:]
    if "--all" in args:
        root = Path(args[args.index("--all") + 1])
        schema = apischema.Schema()
        for lang in LANGS:
            p = root / lang / FILES[lang]
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(generate(lang, schema))
            print(f"{p}")
        return
    lang = args[args.index("--lang") + 1] if "--lang" in args else "ts"
    if lang not in LANGS:
        raise SystemExit(f"--lang is one of {' '.join(LANGS)}")
    text = generate(lang)
    if "-o" in args:
        Path(args[args.index("-o") + 1]).write_text(text)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
