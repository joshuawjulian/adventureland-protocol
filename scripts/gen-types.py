#!/usr/bin/env python3
"""Writes typed definitions of the socket API from schema/ (see docs/WRITING.md, "Typed
definitions from the schema").

    python3 scripts/gen-types.py                       # TypeScript to stdout
    python3 scripts/gen-types.py --lang python         # ts python go csharp rust java
    python3 scripts/gen-types.py --lang go -o al.go    # to a file
    python3 scripts/gen-types.py --all DIR             # every language into DIR/<lang>/...

All seven languages render the same list of declarations, `apischema.model(schema)`: the named
types of schema/types.json and of the event files, then per event you send its request (a
discriminated union for an event with variants), each reply, and its failure union, then per
event you receive its payload. TypeScript is in apischema.py (`typescript()`); the six others are
here. scripts/check-types.py compiles each output in Docker (tsc --strict, mypy --strict,
go vet + go build, dotnet build, cargo build, mvn compile).

How the schema maps (the table in docs/WRITING.md):

- An object type becomes a TypedDict / struct / record. A type that `extends` another gets the
  base fields copied in (flattened): Python TypedDicts cannot narrow an inherited field, Go and
  Rust have no inheritance, and Java records cannot extend. A field of the type replaces the
  base field of the same name.
- A literal becomes its primitive (`"buy"` -> string) except in Python (`Literal["buy"]`); a
  union of literals of one primitive becomes that primitive; `T | null` becomes an optional /
  nullable T.
- A union of different shapes becomes the language's "any JSON" type (json.RawMessage,
  JsonElement, serde_json::Value, JsonNode), except in Python (a real union) and Rust (an
  `#[serde(untagged)]` enum for the unions the model declares: requests and failures).
- `integer` / `number` become int / float (int64 / float64, long / double, i64 / f64).
- Optional fields: NotRequired (Python), pointer + omitempty (Go), nullable (C#, Java),
  Option + skip_serializing_if (Rust).
"""

