# ---------------------------------------------------------------------------------------------
# Shared helpers: flattening, primitive analysis, names
# ---------------------------------------------------------------------------------------------


class Lang:
    """What every language generator shares: the model, the flattened fields of each object
    declaration, and the analysis of type trees."""

    def __init__(self, schema):
        self.schema = schema
        self.m = apischema.model(schema)
        self.objects = {n: b for k, n, d, b in self.m.decls if k == "object"}
        self.aliases = {n: b for k, n, d, b in self.m.decls if k == "alias"}
        self.unions = {n: b for k, n, d, b in self.m.decls if k == "union"}

    def fields(self, body):
        """The fields of an object declaration, the base fields first (flattened)."""
        base = []
        if body.get("extends"):
            base = self.fields(self.objects[body["extends"]])
        own = body["fields"]
        names = {f["name"] for f in own}
        return [f for f in base if f["name"] not in names] + own

    def is_open(self, body):
        return body["open"] or bool(body.get("extends") and self.is_open(self.objects[body["extends"]]))

    def target(self, name, seen=()):
        """What a declared name stands for: ("object", name), ("prim", p), ("tree", tree) for an
        alias, ("union", name) for a declared union."""
        if name in self.objects:
            return ("object", name)
        if name in self.unions:
            return ("union", name)
        if name in self.aliases and name not in seen:
            return ("tree", parse_type(self.aliases[name]))
        return ("prim", "any")

    def prim(self, tree, seen=()):
        """The one primitive a tree always is ("string", "integer", "number", "boolean", "null"),
        through aliases and unions of literals; None when it is not one primitive."""
        kind = tree[0]
        if kind == "lit":
            v = tree[1]
            return "boolean" if isinstance(v, bool) else "string" if isinstance(v, str) else \
                "integer" if isinstance(v, int) else "number"
        if kind == "prim":
            return tree[1] if tree[1] in ("string", "integer", "number", "boolean", "null") else None
        if kind == "ref":
            if tree[1] in seen:
                return None
            t = self.target(tree[1])
            return self.prim(t[1], seen + (tree[1],)) if t[0] == "tree" else None
        if kind == "union":
            ps = {self.prim(t, seen) for t in tree[1]}
            if None in ps:
                return None
            if ps == {"integer", "number"}:
                return "number"
            return ps.pop() if len(ps) == 1 else None
        return None

    @staticmethod
    def split_null(tree):
        """(tree without null, nullable?) for `T | null`."""
        if tree[0] == "union" and ("prim", "null") in tree[1]:
            rest = [t for t in tree[1] if t != ("prim", "null")]
            return (rest[0] if len(rest) == 1 else ("union", rest)), True
        return tree, False


def doc_text(text):
    return re.sub(r"\s+", " ", text or "").strip()


def wrap(text, width=96, prefix=""):
    """A comment block, wrapped."""
    words, lines, line = doc_text(text).split(" "), [], ""
    for w in words:
        if line and len(line) + 1 + len(w) > width - len(prefix):
            lines.append(line)
            line = w
        else:
            line = f"{line} {w}" if line else w
    if line:
        lines.append(line)
    return [prefix + x for x in lines] or [prefix.rstrip()]


def unique_names(names, make, reserved=()):
    """Maps each JSON key to an identifier made by `make`, unique within one type."""
    out, taken = {}, set(reserved)
    for n in names:
        ident = make(n)
        while ident in taken:
            ident += "_"
        taken.add(ident)
        out[n] = ident
    return out


