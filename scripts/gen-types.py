def snake(name):
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)
    s = re.sub(r"[^A-Za-z0-9]+", "_", s).strip("_").lower() or "field"
    if s[0].isdigit():
        s = "n_" + s
    return "r#" + s if s in RUST_KEYWORDS and s not in ("self", "Self", "super", "crate") else (s + "_" if s in ("self", "super", "crate") else s)


class Rust(Lang):
    PRIM = {"string": "String", "integer": "i64", "number": "f64", "boolean": "bool",
            "null": "Value", "any": "Value", "object": "Map<String, Value>"}

    def t(self, tree):
        tree, nullable = self.split_null(tree)
        inner = self._t(tree)
        return f"Option<{inner}>" if nullable else inner

    def _t(self, tree):
        # String literals (and unions of them) become enums with one renamed unit variant per
        # value, so an untagged enum (a failure union) picks the variant whose `response` and
        # `place` really match, not the first one with a String there.
        strs = self.str_lits(tree)
        if strs:
            return self.lit_enum(strs)
        p = self.prim(tree)
        if p:
            return self.PRIM[p]
        kind = tree[0]
        if kind == "prim":
            return self.PRIM[tree[1]]
        if kind == "ref":
            return tree[1]
        if kind == "array":
            return f"Vec<{self.t(tree[1])}>"
        if kind == "record":
            return f"HashMap<String, {self.t(tree[1])}>"
        if kind == "tuple":
            return "(" + ", ".join(self.t(x) for x in tree[1]) + ("," if len(tree[1]) == 1 else "") + ")"
        return "Value"

    enums = None

    @staticmethod
    def str_lits(tree):
        if tree[0] == "lit" and isinstance(tree[1], str):
            return [tree[1]]
        if tree[0] == "union" and all(x[0] == "lit" and isinstance(x[1], str) for x in tree[1]):
            return list(dict.fromkeys(x[1] for x in tree[1]))
        return None

    def lit_enum(self, values):
        key = tuple(sorted(values))
        if key not in self.enums:
            base = "Lit" + "".join(pascal(v) or "Empty" for v in key[:3]) + ("Etc" if len(key) > 3 else "")
            name, i = base, 2
            while name in self.enum_names or name in self.objects or name in self.aliases or name in self.unions:
                name, i = f"{base}{i}", i + 1
            self.enum_names.add(name)
            self.enums[key] = (name, values)
        return self.enums[key][0]

    def enum_decls(self):
        out = []
        for name, values in self.enums.values():
            out.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]")
            out.append(f"pub enum {name} {{")
            for i, v in enumerate(values):
                ident = pascal(v) or "Empty"
                if not ident[0].isalpha():
                    ident = "V" + ident
                out.append(f"    #[serde(rename = {json.dumps(v)})]")
                out.append(f"    {ident}{'' if ident not in [pascal(x) for x in values[:i]] else i},")
            out.append("}")
            out.append("")
        return out

    def render(self):
        self.enums, self.enum_names = {}, set()
        body = self.render_body()
        head = body[:body.index("")]
        return "\n".join(head + [""] + self.enum_decls() + body[len(head):])

    def render_body(self):
        out = [f"// {HEADER}", "#![allow(dead_code, non_camel_case_types, clippy::all)]",
               "use serde::{Deserialize, Serialize};", "use serde_json::{Map, Value};",
               "use std::collections::HashMap;", ""]
        for kind, name, doc, body in self.m.decls:
            out += wrap(doc, prefix="/// ")
            if kind == "object":
                fs = self.fields(body)
                idents = unique_names([f["name"] for f in fs], snake, {"extra"})
                out.append("#[derive(Debug, Clone, Serialize, Deserialize)]")
                out.append(f"pub struct {name} {{")
                for f in fs:
                    tree, nullable = self.split_null(parse_type(f["type"]))
                    t = self._t(tree)
                    if t in self.objects:
                        # Box: a struct may not hold itself by value, also through a chain.
                        t = f"Box<{t}>"
                    attrs = [f"rename = {json.dumps(f['name'])}"]
                    if f.get("optional") or nullable:
                        t = f"Option<{t}>"
                        attrs += ["default", 'skip_serializing_if = "Option::is_none"']
                    out.append(f"    #[serde({', '.join(attrs)})]")
                    out.append(f"    pub {idents[f['name']]}: {t},")
                if self.is_open(body):
                    out.append("    /// The keys this struct does not name.")
                    out.append("    #[serde(flatten)]")
                    out.append("    pub extra: Map<String, Value>,")
                out.append("}")
            elif kind == "alias":
                t = self.t(parse_type(body))
                out.append(f"pub type {name} = {'Value' if t == name else t};")
            else:
                trees = [parse_type(x) for x in body]
                p = self.prim(("union", trees))
                if p:
                    out.append(f"pub type {name} = {self.PRIM[p]};")
                else:
                    # Untagged: serde tries each variant in order. Bare codes are one String.
                    out.append("#[derive(Debug, Clone, Serialize, Deserialize)]")
                    out.append("#[serde(untagged)]")
                    out.append(f"pub enum {name} {{")
                    # Bare codes (string literals) are one variant: an enum of the codes.
                    codes = [v for tree in trees for v in (self.str_lits(tree) or [])]
                    for x, tree in zip(body, trees):
                        if tree[0] == "ref" and tree[1] in self.objects:
                            out.append(f"    {x}(Box<{x}>),")
                        elif tree[0] == "ref":
                            out.append(f"    {x}({self.t(tree)}),")
                        elif not self.str_lits(tree):
                            out.append(f"    V{pascal(x) or 'Value'}({self.t(tree)}),")
                    if codes:
                        out.append(f"    Code({self.lit_enum(list(dict.fromkeys(codes)))}),")
                    out.append("}")
            out.append("")
        return out


