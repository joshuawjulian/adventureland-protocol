class CSharp(Lang):
    PRIM = {"string": "string", "integer": "long", "number": "double", "boolean": "bool",
            "null": "JsonElement", "any": "JsonElement", "object": "Dictionary<string, JsonElement>"}

    def t(self, tree, seen=()):
        tree, _ = self.split_null(tree)
        p = self.prim(tree)
        if p:
            return self.PRIM[p]
        kind = tree[0]
        if kind == "prim":
            return self.PRIM[tree[1]]
        if kind == "ref":
            tg = self.target(tree[1], seen)
            if tg[0] == "object":
                return tree[1]
            if tg[0] == "tree" and tree[1] not in seen:
                return self.t(tg[1], seen + (tree[1],))
            return "JsonElement"
        if kind == "array":
            return f"List<{self.t(tree[1], seen)}>"
        if kind == "record":
            return f"Dictionary<string, {self.t(tree[1], seen)}>"
        return "JsonElement"

    def render(self):
        out = [f"// {HEADER}", "#nullable enable", "using System.Collections.Generic;",
               "using System.Text.Json;", "using System.Text.Json.Serialization;", "",
               "namespace AlApi;", ""]
        for kind, name, doc, body in self.m.decls:
            out.append("/// <summary>" + doc_text(f"{doc}").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;") + "</summary>")
            if kind == "object":
                fs = self.fields(body)

                def ident(n):
                    p = pascal(n) or "Field"
                    if not p[0].isalpha():
                        p = "_" + p
                    return p + ("Value" if p == name else "")
                idents = unique_names([f["name"] for f in fs], ident, {"Extra", name})
                out.append(f"public sealed record {name}")
                out.append("{")
                for f in fs:
                    tree, nullable = self.split_null(parse_type(f["type"]))
                    t = self.t(tree)
                    opt = f.get("optional") or nullable
                    req = "" if opt else "required "
                    out.append(f"    [JsonPropertyName({json.dumps(f['name'])})] public {req}{t}{'?' if opt else ''} "
                               f"{idents[f['name']]} {{ get; init; }}")
                if self.is_open(body):
                    out.append("    [JsonExtensionData] public Dictionary<string, JsonElement>? Extra { get; init; }")
                out.append("}")
            else:
                # Aliases and unions are inlined where they are used; the name is kept as a
                # comment so a reader can find it.
                what = body if kind == "alias" else " | ".join(body)
                out.append(f"// {name} = {what} (inlined at each use as {self.t(parse_type(what) if kind == 'alias' else ('union', [parse_type(x) for x in body]))})")
            out.append("")
        return "\n".join(out)


