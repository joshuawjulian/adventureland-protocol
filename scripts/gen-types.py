class Python(Lang):
    def t(self, tree):
        kind = tree[0]
        if kind == "prim":
            return {"string": "str", "integer": "int", "number": "float", "boolean": "bool",
                    "null": "None", "any": "Any", "object": "dict[str, Any]"}[tree[1]]
        if kind == "lit":
            return f"Literal[{json.dumps(tree[1]) if not isinstance(tree[1], bool) else tree[1]}]"
        if kind == "ref":
            return tree[1]
        if kind == "array":
            return f"list[{self.t(tree[1])}]"
        if kind == "record":
            return f"dict[str, {self.t(tree[1])}]"
        if kind == "tuple":
            return "tuple[" + ", ".join(self.t(x) for x in tree[1]) + "]"
        if kind == "union":
            lits = [x[1] for x in tree[1] if x[0] == "lit"]
            rest = [self.t(x) for x in tree[1] if x[0] != "lit"]
            parts = ([f"Literal[{', '.join(json.dumps(v) if not isinstance(v, bool) else str(v) for v in lits)}]"]
                     if lits else []) + rest
            return " | ".join(dict.fromkeys(parts))
        raise ValueError(tree)

    def render(self):
        out = [f"# {HEADER}", "# Each type is a TypedDict (functional syntax: some JSON keys are Python keywords).",
               "# The annotations are strings, so the order of the definitions does not matter.",
               "from __future__ import annotations", "",
               "from typing import Any, Literal, TypedDict", "",
               "from typing_extensions import NotRequired, TypeAlias", ""]
        for kind, name, doc, body in self.m.decls:
            out += wrap(doc, prefix="# ")
            if kind == "object":
                items = []
                for f in self.fields(body):
                    t = self.t(parse_type(f["type"]))
                    if f.get("optional"):
                        t = f"NotRequired[{t}]"
                    items.append(f"    {json.dumps(f['name'])}: {json.dumps(t)},")
                if self.is_open(body):
                    out.append("# The object can have more keys than these (a TypedDict cannot say so).")
                out.append(f"{name} = TypedDict({json.dumps(name)}, {{" + ("\n" + "\n".join(items) + "\n" if items else "") + "})")
            elif kind == "alias":
                out.append(f"{name}: TypeAlias = {json.dumps(self.t(parse_type(body)))}")
            else:
                out.append(f"{name}: TypeAlias = {json.dumps(' | '.join(self.t(parse_type(x)) for x in body))}")
            out.append("")
        # The event maps, as plain dicts of names (Python has no type-level map).
        out.append("# Client to server: event name -> the request type name (None: no payload).")
        out.append("CLIENT_EVENTS: dict[str, str | None] = {")
        out += [f"    {json.dumps(e)}: {json.dumps(t) if t else None}," for e, t in self.m.client]
        out.append("}")
        out.append("# Server to client: event name -> the payload type name.")
        out.append("SERVER_EVENTS: dict[str, str] = {")
        out += [f"    {json.dumps(e)}: {json.dumps(t)}," for e, t in self.m.server.items()]
        out.append("}")
        return "\n".join(out) + "\n"


